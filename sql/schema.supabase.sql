-- PostgreSQL schema for Supabase SQL Editor.
-- This file is also mirrored in schema.sql for easy use in the Supabase SQL Editor.

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id VARCHAR(128) NOT NULL UNIQUE,
  name VARCHAR(100),
  location VARCHAR(150),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS search_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id VARCHAR(128) NOT NULL,
  type VARCHAR(32) NOT NULL,
  query_text VARCHAR(500) NOT NULL,
  result_json JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_search_device_created ON search_history (device_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_search_type ON search_history (type);

CREATE TABLE IF NOT EXISTS youtube_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id VARCHAR(128) NOT NULL,
  video_id VARCHAR(64) NOT NULL,
  title VARCHAR(500) NOT NULL,
  channel VARCHAR(255),
  url VARCHAR(1000),
  played_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_yt_device_played ON youtube_history (device_id, played_at DESC);
CREATE INDEX IF NOT EXISTS idx_yt_video ON youtube_history (video_id);

CREATE TABLE IF NOT EXISTS favorites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id VARCHAR(128) NOT NULL,
  video_id VARCHAR(64) NOT NULL,
  title VARCHAR(500) NOT NULL,
  channel VARCHAR(255),
  url VARCHAR(1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_favorite UNIQUE (device_id, video_id)
);

CREATE TABLE IF NOT EXISTS weather_cache (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city VARCHAR(150) NOT NULL UNIQUE,
  latitude NUMERIC(10,6) NOT NULL,
  longitude NUMERIC(10,6) NOT NULL,
  data_json JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS news_cache (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  keyword VARCHAR(255) NOT NULL UNIQUE,
  data_json JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS reminders (
  id UUID PRIMARY KEY,
  device_id VARCHAR(128) NOT NULL,
  title VARCHAR(120) NOT NULL,
  due_at TIMESTAMPTZ(3) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_reminder_device_due ON reminders (device_id, due_at);

